const LIBRARY_BY_ID = new Map(EXERCISE_LIBRARY.map(e => [e.id, e]));

/** Resolve library id from a stored English (or alias) name. */
function resolveIdFromName(name: string | null | undefined): string | undefined {
  const needle = name?.trim().toLowerCase();
  if (!needle) {
    return undefined;
  }
  const exact = EXERCISE_LIBRARY.find(e => e.name.toLowerCase() === needle);
  if (exact) {
    return exact.id;
  }
  const alias = EXERCISE_LIBRARY.find(e =>
    (e.aliases ?? []).some(a => a.toLowerCase() === needle),
  );
  return alias?.id;
}

export function getExerciseDisplayName(params: {
  exerciseId?: string | null;
  fallbackName: string;
  language: AppLanguage;
}): string {
  const id =
    params.exerciseId?.trim() ||
    resolveIdFromName(params.fallbackName) ||
    undefined;

  if (id) {
    const override = EXERCISE_NAME_OVERRIDES[params.language]?.[id];
    if (override) {
      return override;
    }
    const fromLib = LIBRARY_BY_ID.get(id);
    if (fromLib?.name) {
      return fromLib.name;
    }
  }
  return params.fallbackName;
}
